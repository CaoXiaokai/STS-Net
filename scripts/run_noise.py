import argparse
import csv
import gc
import hashlib
import math
import os
import sys
from pathlib import Path
import numpy as np
import torch
from noise_common import (
    PACKAGE_ROOT, FORMAT_ID, CONDITIONS, task_specs, task_id, read_json, write_json,
    sha256, validate_config, ensure_inside,
)

sys.path.insert(0, str(PACKAGE_ROOT / "code"))
import train as native


def state_hash(state):
    digest = hashlib.sha256()
    for name, tensor in sorted(state.items()):
        array = tensor.detach().cpu().contiguous().numpy()
        digest.update(name.encode())
        digest.update(str(array.dtype).encode())
        digest.update(str(array.shape).encode())
        digest.update(array.tobytes())
    return digest.hexdigest()


def code_hashes():
    paths = [PACKAGE_ROOT / "code/train.py", Path(__file__),
             PACKAGE_ROOT / "scripts/noise_common.py"]
    paths += sorted((PACKAGE_ROOT / "code/stsnet").glob("*.py"))
    return {path.relative_to(PACKAGE_ROOT).as_posix(): sha256(path) for path in paths}


def verify_manifest(root, manifest):
    if manifest.get("format") != FORMAT_ID or manifest.get("models") != 63:
        raise ValueError("Use a manifest generated by this package's prepare_noise.py")
    validate_config(manifest["training_config"])
    expected = [(task_id(k, s, u), k, s, u) for k, s, u in task_specs()]
    actual = [(t["task_id"], t["noise_kind"], t["snr_db"], t["subject"]) for t in manifest["tasks"]]
    if actual != expected:
        raise ValueError("Task order or scope differs from the seven-condition paper panel")
    for task in manifest["tasks"]:
        expected_folder = f"conditions/{task['noise_kind']}_{int(task['snr_db'])}dB/A{task['subject']:02d}"
        if task["folder"] != expected_folder:
            raise ValueError(f"Unexpected task folder: {task['folder']}")
        expected_artifacts = {f"{expected_folder}/job.json", f"{expected_folder}/noise_recipe.npz"}
        expected_artifacts.update(f"{expected_folder}/data/BCI-38/A{task['subject']:02d}{suffix}.mat"
                                  for suffix in ("T", "E"))
        if set(task["artifact_sha256"]) != expected_artifacts:
            raise ValueError("Prepared task must include exactly its recipe, job, and T/E data hashes")
        for relative, digest in task["artifact_sha256"].items():
            if sha256(ensure_inside(root, relative)) != digest:
                raise ValueError(f"Prepared input changed: {relative}")
        job = read_json(ensure_inside(root, task["folder"]) / "job.json")
        for key in ("task_id", "noise_kind", "snr_db", "subject"):
            if job[key] != task[key]:
                raise ValueError(f"Job identity mismatch: {task['task_id']}")
        if job["source_kind"] != "new_training" or job["resume"]:
            raise ValueError("Old models and checkpoint resume are not part of this panel")


def task_config(root, task, manifest):
    folder = ensure_inside(root, task["folder"])
    return dict(manifest["training_config"], subjects=str(task["subject"]),
                data_root=str(folder / "data"), run_dir=str(folder / "training"), resume=False)


def audit_task(root, task, manifest, implementation):
    folder = ensure_inside(root, task["folder"])
    output = folder / "training" / f"2A_S{task['subject']:02d}"
    config = read_json(folder / "training/config.json")
    assert config == task_config(root, task, manifest)
    with (output / "epochs.csv").open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    assert len(rows) == 2000 and [int(row["epoch"]) for row in rows] == list(range(1, 2001))
    assert all(math.isfinite(float(value)) for row in rows for value in row.values())
    best_row = min(rows, key=lambda row: (-round(float(row["test_acc"]) * 288), int(row["epoch"])))
    best = torch.load(output / "best_model.pt", map_location="cpu", weights_only=False)
    latest = torch.load(output / "latest_checkpoint.pt", map_location="cpu", weights_only=False)
    metadata = {"format": FORMAT_ID, "task_id": task["task_id"],
                "noise_kind": task["noise_kind"], "snr_db": task["snr_db"],
                "subject": task["subject"], "base_seed": 7, "subject_seed": 7 + task["subject"],
                "fully_retrained": True, "source_kind": "new_training"}
    for checkpoint in (best, latest):
        assert checkpoint["args"] == config and checkpoint["subject"] == task["subject"]
        assert checkpoint["paper_noise_experiment"] == metadata
    assert latest["epoch"] == 2000 and best["metrics"]["epoch"] == int(best_row["epoch"])
    for key in best["metrics"]:
        assert float(best["metrics"][key]) == float(best_row[key]) == float(latest["best"][key])
    for key in latest["latest"]:
        assert float(latest["latest"][key]) == float(rows[-1][key])
    assert read_json(output / "summary.json")["best"] == best["metrics"]
    data = native.load_subject(config["data_root"], "BCI-38", "2a", task["subject"], norm_mode="channel")
    pred, labels = latest["best_pred"].numpy(), latest["best_target"].numpy()
    assert pred.shape == labels.shape == (288,) and np.array_equal(labels, data.test_y.numpy())
    assert np.all((pred >= 0) & (pred < 4))
    cm = np.bincount(4 * labels + pred, minlength=16).reshape(4, 4)
    assert np.array_equal(cm.sum(axis=1), [72]*4)
    assert cm.trace() / 288 == float(best_row["test_acc"])
    assert native.cohen_kappa(latest["best_pred"], latest["best_target"], 4) == float(best_row["test_kappa"])
    initialization = read_json(folder / "training/initialization.json")
    assert initialization["subject_seed"] == 7 + task["subject"]
    assert initialization["loaded_checkpoint"] is False
    assert initialization["implementation_sha256"] == implementation
    # A receipt can skip this task only when all data and result hashes still match.
    artifacts = [output / "best_model.pt", output / "latest_checkpoint.pt", output / "epochs.csv",
                 output / "summary.json", folder / "training/config.json",
                 folder / "training/initialization.json"]
    receipt = {"format": FORMAT_ID, "task_id": task["task_id"], "status": "passed",
               "source_kind": "new_training", "noise_kind": task["noise_kind"],
               "snr_db": task["snr_db"], "subject": task["subject"],
               "training_rows": 2000, "selected_epoch": int(best_row["epoch"]),
               "accuracy": float(best_row["test_acc"]), "kappa": float(best_row["test_kappa"]),
               "initialization_sha256": initialization["state_sha256"],
               "input_sha256": task["artifact_sha256"], "implementation_sha256": implementation,
               "artifact_sha256": {p.relative_to(root).as_posix(): sha256(p) for p in artifacts}}
    return receipt


def accepted_task(root, task, manifest, implementation):
    receipt_path = ensure_inside(root, task["folder"]) / "completion.json"
    if not receipt_path.exists():
        return None
    receipt = read_json(receipt_path)
    if receipt["format"] != FORMAT_ID or receipt["task_id"] != task["task_id"]:
        raise ValueError("Completion receipt belongs to a different task")
    if receipt["input_sha256"] != task["artifact_sha256"] or receipt["implementation_sha256"] != implementation:
        raise ValueError("Existing completion is from different inputs or implementation")
    for relative, digest in receipt["artifact_sha256"].items():
        if sha256(ensure_inside(root, relative)) != digest:
            raise ValueError(f"Completed artifact changed: {relative}")
    if audit_task(root, task, manifest, implementation) != receipt:
        raise ValueError("Completed task failed independent record/metric audit")
    return receipt


def aggregate(root, manifest, implementation):
    rows = []
    initialization_by_subject = {}
    for task in manifest["tasks"]:
        receipt = accepted_task(root, task, manifest, implementation)
        if receipt is None:
            raise RuntimeError("All 63 tasks must pass audit before aggregate results are written")
        subject = task["subject"]
        if subject in initialization_by_subject:
            assert initialization_by_subject[subject] == receipt["initialization_sha256"]
        initialization_by_subject[subject] = receipt["initialization_sha256"]
        rows.append({"kind": task["noise_kind"], "snr_db": task["snr_db"],
                     "subject": f"A{subject:02d}", "accuracy": receipt["accuracy"],
                     "kappa": receipt["kappa"], "selected_epoch": receipt["selected_epoch"]})
    with (root / "subject_results.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)
    means = []
    for kind, snr in CONDITIONS:
        group = [row for row in rows if row["kind"] == kind and row["snr_db"] == snr]
        assert len(group) == 9
        means.append({"kind": kind, "snr_db": snr,
                      "average_accuracy": float(np.mean([row["accuracy"] for row in group])),
                      "average_kappa": float(np.mean([row["kappa"] for row in group]))})
    with (root / "condition_results.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(means[0]))
        writer.writeheader(); writer.writerows(means)
    write_json(root / "results.json", {"format": FORMAT_ID, "status": "completed", "models": 63,
               "reused_results": 0, "subject_results": rows, "condition_results": means})


def run_task(root, task, manifest, implementation):
    folder = ensure_inside(root, task["folder"])
    train_root = folder / "training"
    if train_root.exists():
        raise FileExistsError(f"Unaccepted training output exists: {train_root}. No automatic resume or retraining.")
    train_root.mkdir()
    config = task_config(root, task, manifest)
    write_json(train_root / "config.json", config)
    original_model, original_save = native.STSNet, native.atomic_torch_save

    def factory(*args, **kwargs):
        model = original_model(*args, **kwargs)
        write_json(train_root / "initialization.json", {
            "state_sha256": state_hash(model.state_dict()),
            "torch_cpu_rng_sha256": hashlib.sha256(torch.get_rng_state().numpy().tobytes()).hexdigest(),
            "subject_seed": 7 + task["subject"], "loaded_checkpoint": False,
            "implementation_sha256": implementation})
        return model

    def save(obj, path):
        metadata = {"format": FORMAT_ID, "task_id": task["task_id"],
                    "noise_kind": task["noise_kind"], "snr_db": task["snr_db"],
                    "subject": task["subject"], "base_seed": 7, "subject_seed": 7 + task["subject"],
                    "fully_retrained": True, "source_kind": "new_training"}
        original_save(dict(obj, paper_noise_experiment=metadata), path)
        if path.name == "latest_checkpoint.pt":
            write_json(root / "progress.json", {"task_id": task["task_id"], "epoch": obj["epoch"], "status": "running"})
            if (root / "STOP_AFTER_CHECKPOINT").exists():
                raise RuntimeError("Stop requested after checkpoint save; this incomplete task will not auto-resume")

    try:
        native.STSNet, native.atomic_torch_save = factory, save
        native.train_one_subject(argparse.Namespace(**config), task["subject"], train_root)
    finally:
        native.STSNet, native.atomic_torch_save = original_model, original_save
    receipt = audit_task(root, task, manifest, implementation)
    write_json(folder / "completion.json", receipt)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", required=True, type=Path, help="Directory created by prepare_noise.py")
    parser.add_argument("--dry-run", action="store_true", help="Validate inputs and list tasks without training")
    parser.add_argument("--aggregate-only", action="store_true", help="Audit completed tasks and rebuild CSV tables only")
    args = parser.parse_args()
    root = args.run_dir.resolve()
    manifest = read_json(root / "manifest.json")
    verify_manifest(root, manifest)
    implementation = code_hashes()
    if args.dry_run:
        for task in manifest["tasks"]:
            print(task["task_id"])
        print("63 tasks validated. No model trained and no checkpoint loaded.")
        return
    if args.aggregate_only:
        aggregate(root, manifest, implementation)
        return
    if not torch.cuda.is_available():
        raise RuntimeError("The recorded experiment used CUDA AMP. A CUDA device is required; no silent CPU fallback.")
    lock_path = root / ".training.lock"
    with lock_path.open("x", encoding="utf-8") as lock:
        lock.write(str(os.getpid()))
    try:
        torch.set_num_threads(8)
        for index, task in enumerate(manifest["tasks"], 1):
            if (root / "STOP_AFTER_CHECKPOINT").exists():
                raise RuntimeError("Stop marker present")
            if accepted_task(root, task, manifest, implementation) is not None:
                print(f"Verified completed task {index}/63: {task['task_id']}", flush=True)
                continue
            print(f"Training fresh task {index}/63: {task['task_id']}", flush=True)
            run_task(root, task, manifest, implementation)
            gc.collect(); torch.cuda.empty_cache()
        aggregate(root, manifest, implementation)
        write_json(root / "progress.json", {"status": "completed", "completed": 63, "total": 63})
    finally:
        # Remove only the exact lock created by this process; interrupted tasks
        # remain on disk and cannot be silently resumed or overwritten.
        lock_path.unlink()


if __name__ == "__main__":
    main()
